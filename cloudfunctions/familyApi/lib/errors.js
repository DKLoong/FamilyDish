// 可预期的业务错误。抛出后由 index.js 统一转换为 { success:false, code, message }。
// 未捕获的错误一律折叠为 INTERNAL_ERROR，不把堆栈或数据库细节返回给前端。
class ApiError extends Error {
  constructor(code, message) {
    super(message || code)
    this.name = 'ApiError'
    this.code = code
  }
}

